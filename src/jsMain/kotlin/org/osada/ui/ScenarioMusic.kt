package org.osada.ui

import org.osada.ui.music.MusicCatalog

/**
 * OG's **custom scenario music** — `.xscn` `@127`, a NUL-terminated track name gated on
 * `opt_custom_music` (`@1009` bit 6). **81 deployed scenarios author one**, 688 corpus-wide across
 * 62 distinct names (`winter.mp3`, `amb_field.mp3`, `japan1.MUS`, `PG1.mp3`); OG resolves each in
 * the naming scenario's OWN efile `SOUND` directory and in the install's root `SOUND`, and nowhere
 * else — which is why a name that exists only in some other efile means silence, not that file.
 *
 * ## Licensed subset and manifest gate
 *
 * `README/read_me_first.html` in the OG install forbids redistributing sounds without the owner's
 * written permission. That permission was confirmed by the repository owner on 2026-09-01. Two
 * referenced MP3s now ship with a manifest at [MANIFEST_URL] and cover 23 scenarios — 21 from
 * their own efile, plus the two `eqp-olgcw` scenarios that
 * name `AFRICA2.mp3`, which is a recorded substitution rather than their author's file (see
 * `sounds/music/NOTICE.md`). Five referenced names have no source file in that install; they remain
 * silent, and the manifest prevents any request or 404 for them. `campsimpob.mp3` is deliberately
 * excluded, leaving its 24 authored scenario references inert but available as configuration
 * examples (see `sounds/music/NOTICE.md`).
 *
 * ## Two normalisations, and why they are here rather than in the importer
 *
 * * **Case.** OG runs on Windows, where `Winter.MP3` and `winter.mp3` are the same file; the
 *   deployed web server is case-sensitive. Names are matched lower-cased.
 * * **Format.** `.MUS` is a DOS-era tracker format no browser plays, and 62 distinct authored names
 *   include several. A track whose extension is not [PLAYABLE] is refused rather than requested.
 *
 * Both are runtime concerns rather than import ones: `add_custom_music.py` deploys the author's own
 * string so the XML stays a faithful record of what was written, and a future converted `.ogg`
 * changes only the manifest.
 *
 * African Drums participates in an explicitly mapped ordinary music preset. Park routes to
 * ScenarioAmbience and never resolves as music. Missing tracks remain manifest-gated and silent;
 * no authored musical context can start playback or override a manual pause.
 */
object ScenarioMusic {
    const val MANIFEST_URL = "resources/sounds/music/manifest.json"

    private const val MUSIC_PATH = "resources/sounds/music/"

    /** Extensions a browser will actually decode. `.MUS` is deliberately not among them. */
    private val PLAYABLE = setOf("mp3", "ogg", "m4a", "wav")

    private var available: Set<String>? = null

    /**
     * The URL for [track], or null when it is absent, unplayable, or not listed by the manifest.
     *
     * A cache-only lookup; production uses [resolve] to wait asynchronously for the allow-list.
     * Public so a caller can tell "there is a track" from "it is playing", which the settings screen
     * would need before it can offer to turn scenario music off.
     */
    fun urlFor(track: String?): String? {
        if (isEnvironment(track)) return null
        return legacyUrlFor(track)
    }

    internal fun isEnvironment(track: String?): Boolean = track?.trim()?.lowercase() == "amb_field.mp3"

    private fun legacyUrlFor(track: String?): String? {
        val name = track?.trim()?.lowercase()?.takeIf { it.isNotEmpty() } ?: return null
        return candidates(name).firstOrNull { it in manifest() }?.let { MUSIC_PATH + it }
    }

    /**
     * The file names that may answer for an authored track name, best first.
     *
     * A playable name answers for itself and nothing else. An UNPLAYABLE one -- `.MUS`, the
     * DOS-era tracker format no browser decodes -- may be answered by a converted file of the same
     * stem, because that is the only way the 31 scenarios naming `china1.MUS` and `Jungle_2.MUS`
     * can ever have their author's music: the name is in the scenario XML, which is a faithful
     * record of the source and is regenerated by the importers, so it cannot be edited to point at
     * the conversion.
     *
     * The manifest is still the only gate. A candidate that is not listed is never requested, so a
     * scenario with no conversion available stays silent with no 404, exactly as before.
     */
    private fun candidates(name: String): List<String> {
        val extension = name.substringAfterLast('.', "")
        if (extension in PLAYABLE) return listOf(name)
        val stem = name.substringBeforeLast('.', name)
        return PLAYABLE.map { "$stem.$it" }
    }

    /** Updates authored context only. My mix and a user pause survive every scenario transition. */
    fun play(
        track: String?,
        context: String? = track,
    ) {
        ScenarioAmbience.context(track, context)
    }

    private var loading = false
    private val waiters = mutableListOf<() -> Unit>()

    /** Asynchronous legacy allow-list resolution, shared across concurrent scenario loads. */
    fun resolve(
        track: String?,
        done: (String?) -> Unit,
    ) {
        if (track.isNullOrBlank()) {
            done(null)
            return
        }
        ensureManifest { done(urlFor(track)) }
    }

    internal fun resolveEnvironment(
        track: String?,
        done: (String?) -> Unit,
    ) {
        if (!isEnvironment(track)) {
            done(null)
            return
        }
        ensureManifest { done(legacyUrlFor(track)) }
    }

    private fun manifest(): Set<String> = available ?: emptySet()

    private fun ensureManifest(done: () -> Unit) {
        if (available != null) {
            done()
            return
        }
        waiters.add(done)
        if (loading) return
        loading = true
        MusicCatalog.loadJson(MANIFEST_URL) { data ->
            available = MusicCatalog.strings(data).map { it.lowercase() }.toSet()
            loading = false
            val callbacks = waiters.toList()
            waiters.clear()
            callbacks.forEach { it() }
        }
    }

    /** Installs a manifest without any network access, for tests. */
    internal fun setManifestForTest(names: Set<String>) {
        available = names.map { it.lowercase() }.toSet()
    }

    internal fun resetForTest() {
        available = null
        loading = false
        waiters.clear()
    }
}

/** One environmental source: precipitation wins over the current authored Park loop. */
internal object ScenarioAmbience {
    private var generation = 0
    private var active = false
    private var park: String? = null
    private var sky = 0
    private var contextKey: String? = null
    private var authoredTrack: String? = null

    fun context(
        track: String?,
        key: String?,
    ) {
        if (active && key == contextKey && track == authoredTrack) return
        contextKey = key
        authoredTrack = track
        val token = ++generation
        active = key != null
        park = null
        sky = 0
        Sound.stopAmbient()
        if (!active) return
        ScenarioMusic.resolveEnvironment(track) { url ->
            if (token == generation && active) {
                park = url
                update()
            }
        }
    }

    fun weather(atmospheric: Int) {
        sky = atmospheric
        update()
    }

    private fun update() {
        val url =
            if (!active) {
                null
            } else {
                when (sky) {
                    2 -> "resources/sounds/weather/rain.mp3"
                    3 -> "resources/sounds/weather/winter.mp3"
                    else -> park
                }
            }
        if (url == null) Sound.stopAmbient() else Sound.startAmbient(url)
    }
}
